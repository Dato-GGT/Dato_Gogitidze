type LanguageType = 'en' | 'ru' | 'ge';
interface LangData {
    name: string,
    position: string,
    location: string,
    education: string,
    educationDescription: string,
    experience: string,
    experienceTitle1: string,
    experienceDescription1: string,
    experienceTitle2: string,
    experienceDescription2: string,
    skills: string,
    skillsTitle1: string,
    skillsDescription1: string,
    skillsTitle2: string,
    skillsDescription2: string,
}

class Data {
    private pageTitle: HTMLTitleElement | null = null;
    private nameElement: HTMLElement | null = null;
    private positionElement: HTMLElement | null = null;
    private locationElement: HTMLElement | null = null;
    private educationElement: HTMLElement | null = null;
    private educationDescriptionElement: HTMLElement | null = null;
    private experienceElement: HTMLElement | null = null;
    private experienceTitleElement1: HTMLElement | null = null;
    private experienceDescriptionElement1: HTMLElement | null = null;
    private experienceTitleElement2: HTMLElement | null = null;
    private experienceDescriptionElement2: HTMLElement | null = null;
    private skillsElement: HTMLElement | null = null;
    private skillsTitleElement1: HTMLElement | null = null;
    private skillsDescriptionElement1: HTMLElement | null = null;
    private skillsTitleElement2: HTMLElement | null = null;
    private skillsDescriptionElement2: HTMLElement | null = null;
    private changeLanguageButton: HTMLButtonElement | null = null;
    private language: LanguageType = 'en';

    constructor() {
        this.getElements();
        this.setLanguage();
        this.fillData();
        this.changeLanguageButtonClick();
    }

    private setLanguage(): void {
        const language: string | null = localStorage.getItem('language');
        if (language !== null && (language === 'en' || language === 'ru' || language === 'ge')) {
            this.language = language;
            if (this.changeLanguageButton) this.changeLanguageButton.innerText = this.language;
        }
    }

    private getElements(): void {
        this.pageTitle = document.getElementById('page-title') as HTMLTitleElement;
        this.nameElement = document.getElementById('name');
        this.positionElement = document.getElementById('position');
        this.locationElement = document.getElementById('location');
        this.educationElement = document.getElementById('education');
        this.educationDescriptionElement = document.getElementById('education-description');
        this.experienceElement = document.getElementById('experience');
        this.experienceTitleElement1 = document.getElementById('experience-title-1');
        this.experienceDescriptionElement1 = document.getElementById('experience-description-1');
        this.experienceTitleElement2 = document.getElementById('experience-title-2');
        this.experienceDescriptionElement2 = document.getElementById('experience-description-2');
        this.skillsElement = document.getElementById('skills');
        this.skillsTitleElement1 = document.getElementById('skills-title-1');
        this.skillsDescriptionElement1 = document.getElementById('skills-description-1');
        this.skillsTitleElement2 = document.getElementById('skills-title-2');
        this.skillsDescriptionElement2 = document.getElementById('skills-description-2');
        this.changeLanguageButton = document.getElementById('change-language-button') as HTMLButtonElement;
    }

    private changeLanguageButtonClick(): void {
        if (!this.changeLanguageButton) return;
        this.changeLanguageButton.onclick = () => {
            if (!this.changeLanguageButton) return;

            switch (this.language) {
                case 'en':
                    this.language = 'ru';
                    break;
                case 'ru':
                    this.language = 'ge';
                    break;
                case 'ge':
                    this.language = 'en';
                    break;
            }
            localStorage.setItem('language', this.language);
            this.changeLanguageButton.innerText = this.language;
            this.fillData();
        }
    }

    private fillData(): void {
        this.fillText(this.pageTitle, 'name');
        this.fillText(this.nameElement, 'name');
        this.fillText(this.positionElement, 'position');
        this.fillText(this.locationElement, 'location');
        this.fillText(this.educationElement, 'education');
        this.fillHTML(this.educationDescriptionElement, 'educationDescription');
        this.fillText(this.experienceElement, 'experience');
        this.fillText(this.experienceTitleElement1, 'experienceTitle1');
        this.fillHTML(this.experienceDescriptionElement1, 'experienceDescription1');
        this.fillHTML(this.experienceTitleElement2, 'experienceTitle2');
        this.fillHTML(this.experienceDescriptionElement2, 'experienceDescription2');
        this.fillText(this.skillsElement, 'skills');
        this.fillHTML(this.skillsTitleElement1, 'skillsTitle1');
        this.fillHTML(this.skillsDescriptionElement1, 'skillsDescription1');
        this.fillHTML(this.skillsTitleElement2, 'skillsTitle2');
        this.fillHTML(this.skillsDescriptionElement2, 'skillsDescription2');
    }

    private fillText(element: HTMLElement | null, key: keyof LangData): void {
        if (element) {
            element.innerText = translations[this.language][key];
        }
    }

    private fillHTML(element: HTMLElement | null, key: keyof LangData): void {
        if (element) {
            element.innerHTML = translations[this.language][key];
        }
    }
}

window.onload = () => {
    new Data();
};